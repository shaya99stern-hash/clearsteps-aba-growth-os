/**
 * 150 additional public publishers (35 Missouri, 35 Kansas, 35 Colorado, 20 federal, 25 national).
 * Like every catalog entry these are site-search candidates, not live integrations: a channel only
 * counts as evidence after public search returns a real URL on that host. Hosts were chosen from
 * established public institutions; less familiar domains were confirmed against public search
 * results before inclusion.
 */
type Row = readonly [host: string, kind: string, focus: string, access?: PublicSourceChannel["access"]];

function channels(scope: PublicSourceChannel["scope"], rows: readonly Row[]): PublicSourceChannel[] {
  return rows.map(([host, kind, focus, access]) => ({
    host,
    scope,
    kind,
    method: "site-search" as const,
    focus,
    access: access ?? "public-index",
  }));
}

